// =========================================================
// ヘルパー
// =========================================================

type Operator = '+' | '-' | '×' | '÷';
type Section = { name: string; cases: [id: string, keys: string, expected: string][] };

const KEY_PATTERN = /AC|C|[0-9.+\-×÷=%√±]/g;

/** キー列（例: '10 + 2 ='）を順に押す。空白は無視する。全角風マイナス（−）は - として扱う */
function press(app: App, keys: string): App {
  for (const key of keys.replace(/−/g, '-').match(KEY_PATTERN) ?? []) {
    if (/^[0-9]$/.test(key)) app.inputDigit(key);
    else if (key === '.') app.inputDecimal();
    else if (key === '+' || key === '-' || key === '×' || key === '÷') app.inputOperator(key);
    else if (key === '=') app.calculate();
    else if (key === '%') app.inputPercent();
    else if (key === '√') app.inputSquareRoot();
    else if (key === '±') app.toggleSign();
    else if (key === 'C') app.clear();
    else if (key === 'AC') app.clearAll();
  }
  return app;
}

/** 画面表示を 1 つの文字列にする（例: -E1.50000000 / E0 / -5） */
function show(app: App): string {
  return app.displayPrefix.replace('－', '-') + app.displayExponent + app.displayNumber;
}

function run(keys: string): string {
  return show(press(new App(), keys));
}

/** 再現性のある疑似乱数 */
function makeRng(seed: number): () => number {
  let s = seed;
  return () => {
    s = (s * 1103515245 + 12345) & 0x7fffffff;
    return s / 0x7fffffff;
  };
}

