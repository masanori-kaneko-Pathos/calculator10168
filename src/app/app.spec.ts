// 基準実装（BigInt の厳密計算 + 切り捨て）。四則演算の検証に使う
// =========================================================

const SCALE = 10n ** 8n;

function toScaled(text: string): bigint {
  const [intPart, fracPart = ''] = text.split('.');
  return BigInt(intPart + fracPart.padEnd(8, '0'));
}

/** num/den を実機の表示ルール（整数10桁・小数8桁まで切り捨て、超えたら E 表示）で整形 */
function formatRational(num: bigint, den: bigint): string {
  const negative = (num < 0n) !== (den < 0n) && num !== 0n;
  const n = num < 0n ? -num : num;
  const d = den < 0n ? -den : den;
  const intStr = (n / d).toString();
  const frac = (((n % d) * 10n ** 20n) / d).toString().padStart(20, '0');

  if (intStr.length > 10) {
    const mantissaInt = intStr.slice(0, intStr.length - 10);
    const rest = intStr.slice(intStr.length - 10) + frac;
    const digits = Math.min(8, Math.max(0, 10 - mantissaInt.length));
    const mantissa = digits === 0 ? `${mantissaInt}.` : `${mantissaInt}.${rest.slice(0, digits).padEnd(digits, '0')}`;
    return `${negative ? '-' : ''}E${mantissa}`;
  }

  const digits = intStr === '0' ? 8 : Math.min(8, Math.max(0, 10 - intStr.length));
  const fracStr = frac.slice(0, digits).replace(/0+$/, '');
  const body = fracStr ? `${intStr}.${fracStr}` : intStr;
  return negative && body !== '0' ? `-${body}` : body;
}

function expectedBinary(a: bigint, op: Operator, b: bigint): string {
  switch (op) {
    case '+': return formatRational(a + b, SCALE);
    case '-': return formatRational(a - b, SCALE);
    case '×': return formatRational(a * b, SCALE * SCALE);
    case '÷': return b === 0n ? 'E0' : formatRational(a * SCALE, b * SCALE);
  }
}

function randomOperand(rng: () => number): string {
  const intLen = 1 + Math.floor(rng() * 10);
  let intPart = '';
  for (let i = 0; i < intLen; i++) intPart += Math.floor(rng() * 10);
  intPart = intPart.replace(/^0+(?=\d)/, '');
  const maxDecimals = Math.min(8, 10 - intPart.length);
  if (maxDecimals > 0 && rng() < 0.6) {
    const decimals = 1 + Math.floor(rng() * maxDecimals);
    let fracPart = '';
    for (let i = 0; i < decimals; i++) fracPart += Math.floor(rng() * 10);
    return `${intPart}.${fracPart}`;
  }
  return intPart;
}

